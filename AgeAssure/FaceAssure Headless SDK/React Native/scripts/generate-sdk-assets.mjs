#!/usr/bin/env node
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const demoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sdkDir = join(demoRoot, 'assets/sdk');
const outputPath = join(demoRoot, 'src/sdkAssets.generated.ts');
const writeStub = process.argv.includes('--stub');

const entries = writeStub
  ? []
  : readdirSync(sdkDir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
      .filter((name) => name !== 'index.html');

const bundleName = entries.find((name) => name === 'headless-sdk.bundle');
const wasmFiles = entries.filter((name) => name.endsWith('.wasm')).sort();
const sdkAssetsReady = Boolean(bundleName && wasmFiles.length > 0);

const assetLines = [];

if (bundleName) {
  assetLines.push(
    `  { module: require('../assets/sdk/${bundleName}'), fileName: 'headless-sdk.js' },`,
  );
}

for (const wasmFile of wasmFiles) {
  assetLines.push(
    `  { module: require('../assets/sdk/${wasmFile}'), fileName: '${wasmFile}' },`,
  );
}

const contents = `// Generated by scripts/generate-sdk-assets.mjs — do not edit by hand.
// Run \`npm run generate-sdk-assets\` after copying SDK files into assets/sdk/.

export const SDK_ASSETS_READY = ${sdkAssetsReady};

export const INDEX_HTML_MODULE = require('../assets/sdk/index.html');

export const SDK_ASSETS: Array<{ module: number; fileName: string }> = [
${assetLines.join('\n')}
];
`;

writeFileSync(outputPath, contents, 'utf8');

if (!sdkAssetsReady) {
  if (writeStub) {
    console.log(`Wrote public-repo stub to ${outputPath}.`);
  } else {
    console.warn(
      'SDK binaries not found in assets/sdk/. Add your licensed FaceAssure Headless SDK bundle and WASM files, then re-run this script.',
    );
  }
} else {
  console.log(`Wrote ${outputPath} (${wasmFiles.length} WASM file(s) + bundle).`);
}
